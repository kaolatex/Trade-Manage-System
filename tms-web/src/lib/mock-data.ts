const MIN = 60_000;
const HOUR = 60 * MIN;
const DAY = 24 * HOUR;

function buildEquity(now: number, values: number[]): EquityPoint[] {
  const today = new Date(now);
  today.setHours(0, 0, 0, 0);
  return values.map((equity, i) => ({
    date: today.getTime() - (values.length - i) * DAY,
    equity,
  }));
}

